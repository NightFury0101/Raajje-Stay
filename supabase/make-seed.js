// Builds seed.sql from js/data.js so the database starts with the same listings as the demo.
// Usage: node supabase/make-seed.js > supabase/seed.sql
global.window = {};
require('../js/data.js');
const D = window.RS_DATA;
const q = v => v == null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'";
const arr = a => "array[" + a.map(q).join(',') + "]::text[]";
let out = '-- Generated by supabase/make-seed.js from js/data.js. Sample listings and fares.\n';
out += `insert into settings (key, value) values ('tax', '{"service":10,"tgst":17,"gst":8,"greenHigh":12,"greenLow":6,"greenRoomLimit":50}') on conflict (key) do update set value = excluded.value;\n`;
D.properties.forEach(p => {
  out += `insert into properties (id, name, type, island, rooms_total, rating, reviews, tourist, route, seed, blurb, amenities, status) values (${[p.id, p.name, p.type, p.island, p.roomsTotal, p.rating, p.reviews, p.tourist, p.route, p.seed, p.blurb].map(q).join(', ')}, ${arr(p.amenities)}, 'live') on conflict (id) do nothing;\n`;
  p.rooms.forEach((r, i) => {
    const units = Math.max(1, Math.floor(p.roomsTotal / p.rooms.length));
    out += `insert into room_types (property_id, idx, name, beds, sleeps, size, local_rate, intl_rate, units) values (${[p.id, i, r.name, r.beds, r.sleeps, r.size, r.local, r.intl, units].map(q).join(', ')}) on conflict do nothing;\n`;
  });
});
Object.entries(D.routes).forEach(([route, opts]) => opts.forEach((o, i) => {
  out += `insert into transfer_options (route, idx, mode, origin, mins, times, days, local_fare, intl_fare, via) values (${[route, i, o.mode, o.from, o.mins].map(q).join(', ')}, ${arr(o.times)}, ${[o.days, o.local, o.intl, o.via || null].map(q).join(', ')}) on conflict do nothing;\n`;
}));
